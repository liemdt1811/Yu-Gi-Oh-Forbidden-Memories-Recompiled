#!/usr/bin/env python3
"""Write notes/real-cards-z-recipes.md: how each fusion-only card of the "z" mod is made, step by step.

Reads targets.json: a card's "fusions" (fixed pairs), "steps" (a pair that first makes a middle card)
and "mass" rules (any monster of one group with any of another). A material that is itself one of
these cards is expanded first, so each card reads as a chain from plain monsters up to the card.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[2] / "notes" / "real-cards-z-recipes.md"


def group(g):
    if "name" in g:
        return g["name"]
    text = " ".join(p for p in (g.get("attribute"), g.get("type")) if p) + " monster"
    if "name_has" in g:
        text += f' with "{g["name_has"]}" in its name'
    if "not_name_has" in g:
        text += f' without "{g["not_name_has"]}" in its name'
    return text


def merge(rules):
    """Rules that differ only in the second group's type become one ("Beast/Beast-Warrior")."""
    out = []
    for m in rules:
        for o in out:
            a, b = o["groups"][1], m["groups"][1]
            if (o["groups"][0] == m["groups"][0] and set(a) == set(b) == {"type"} | (set(a) - {"type"})
                    and {k: v for k, v in a.items() if k != "type"} == {k: v for k, v in b.items() if k != "type"}
                    and "type" in a and "type" in b
                    and {k: v for k, v in o.items() if k != "groups"} == {k: v for k, v in m.items() if k != "groups"}):
                a["type"] += "/" + b["type"]
                break
        else:
            out.append(json.loads(json.dumps(m)))
    return out


def mass(m):
    a, b = (group(g) for g in m["groups"])
    cond = f"both up to {m['max_atk']} ATK"
    if "min_one" in m:
        cond += f", one at least {m['min_one']}"
    return f"{a} + {b} ({cond})" + (" - replaces other recipes" if m.get("override") else "")


def main():
    cards = {c["name"]: c for c in json.loads((HERE / "targets.json").read_text(encoding="utf-8"))
             if c.get("fusions") or c.get("mass")}

    def needs(c):
        names = [n for p in c["fusions"] for n in p] + [n for s in c.get("steps", []) for n in s]
        names += [g["name"] for m in c.get("mass", []) for g in m["groups"] if "name" in g]
        return [n for n in dict.fromkeys(names) if n in cards and n != c["name"]]

    def chain(name, seen):
        if name in seen:
            return []
        seen.add(name)
        out = []
        for n in needs(cards[name]):
            out += chain(n, seen)
        return out + [name]

    def lines(n, i):
        c = cards[n]
        rules = merge(c.get("mass", []))
        recipes = [f"{a} + {b}" for a, b in c["fusions"]] + [mass(m) for m in rules if "result" not in m]
        steps = ([f"{s[0]} + {s[1]} = {s[2]}" for s in c.get("steps", [])]
                 + [f"{m['result']} = {mass(m)}" for m in rules if "result" in m])
        head = f"{i}. **{n}** ({c['attack']})"
        if len(recipes) == 1 and not steps:
            return [f"{head} = {recipes[0]}"]
        return ([head + " ="] + [f"   - {r}" for r in recipes] + [f"   - first: {s}" for s in steps])

    out = ["# Z mod: fusion recipes", "",
           f"{len(cards)} cards with a recipe, strongest first. Generated by `tools/pc/real_cards/list_recipes.py` from "
           "`targets.json`. Each chain starts from plain monsters; a bold name is a card of this mod made in an earlier step. "
           "\"X monster\" means any monster of that kind: these mass rules only fill pairs that make nothing yet (unless "
           "marked as replacing). Drops are S/A rank prizes (weight out of 2048).", ""]
    for c in sorted(cards.values(), key=lambda c: (-c["attack"], c["name"])):
        out += [f"## {c['name']} ({c['attack']}/{c['defense']}, {c['attribute']} {c['type']}, Lv{c['level']})", ""]
        for i, n in enumerate(chain(c["name"], set()), 1):
            out += lines(n, i)
        d = c.get("drop")
        out += ["", f"Drop: {', '.join(d['from'])} (weight {d['weight']})" if d else "Drop: none", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{len(cards)} cards -> {OUT}")


if __name__ == "__main__":
    main()
