#!/usr/bin/env python3
"""Write notes/real-cards-list.md: the "z" mod's cards and fusion formulas."""
import csv, json
import modio
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
mod = modio.load(ROOT / "mods/z/mod.json")
cat = {int(r["id"]): r for r in csv.DictReader(open(ROOT / "notes/card-catalog.csv", encoding="utf-8", newline=""))}
new = {f"{mod['id']}:{c['id']}:1": c for c in mod["cards"] if "attack" in c}
spells = {f"{mod['id']}:{c['id']}:1": c for c in mod["cards"] if "attack" not in c}


def label(x):
    if isinstance(x, int):
        return cat[x]["name"], int(cat[x]["attack"])
    return new[x]["name"] + " *", new[x]["attack"]


out = [f"# {mod['name']}: cards and fusions", "",
       f"{len(new)} new monsters, {len(spells)} new Equip and Ritual cards, {len(mod['fusions'])} fusion formulas. `*` marks a new card; "
       "other names are retail cards. Generated by `tools/pc/real_cards/list_cards.py`.", "",
       "## Cards (by ATK, highest first)", "",
       "| # | Name | Type | Attribute | Lv | ATK | DEF | Password | Base card |", "|---|---|---|---|---|---|---|---|---|"]
for i, c in enumerate(sorted(new.values(), key=lambda c: (-c["attack"], c["name"])), 1):
    out.append(f"| {i} | {c['name']} | {c['type']} | {c['attribute']} | {c['level']} | {c['attack']} | "
               f"{c['defense']} | {c['password']} | {cat[c['copy']]['name']} |")
targets = {k: c for k, c in new.items() if not c["drops"]}
won = {}
own = {d["id"] for d in mod.get("duelists", [])}
for opponent, pools in mod.get("drops", {}).items():
    if opponent in own:
        continue
    for pool, cards in pools.items():
        for ref, weight in cards.items():
            won.setdefault(ref, {}).setdefault(weight, set()).add(opponent)
if won:
    out += ["", "## Prizes", "",
            "Fusion-only cards also won on an S or A rank (POW and TEC) from the opponents in the last column. "
            "Weights are out of 2048 per card, per pool.", "",
            "| Card | ATK | Weight | Chance | Opponents |", "|---|---|---|---|---|"]
    both = {**new, **spells}
    for ref, ws in sorted(won.items(), key=lambda kv: (-both[kv[0]].get("attack", -1), both[kv[0]]["name"])):
        (w, opp), = ws.items()
        who = f"{len(opp)} opponents from Teana 2nd on (#20-39)" if len(opp) == 20 else ", ".join(sorted(opp))
        out.append(f"| {both[ref]['name']} | {both[ref].get('attack', '-')} | {w} | {w / 2048:.2%} | {who} |")
out += ["", "## Fusion targets", "",
        "Fusion-only cards from `targets.json`: never dropped or dealt by an opponent.", ""]
for k, c in sorted(targets.items(), key=lambda kv: (-kv[1]["attack"], kv[1]["name"])):
    made = [r for r in mod["fusions"] if r["result"] == k]
    out += [f"### {c['name']} ({c['attack']}) - {len(made)} formulas", ""]
    for r in made[:12]:
        (na, aa), (nb, ab) = label(r["with"][0]), label(r["with"][1])
        out.append(f"- {na} ({aa}) + {nb} ({ab})")
    if len(made) > 12:
        out.append(f"- ... and {len(made) - 12} more of the same kinds (a type with a type, weak materials)")
    out.append("")
for d in mod.get("duelists", []):
    deck = {k: v for k, v in mod["decks"][d["id"]].items() if k != "replace"}
    nm = lambda r: new.get(r, spells.get(r, {})).get("name", r)
    out += [f"## Duelist: {d['name']}", "",
            f"Free Duel opponent playing like {d['copy']}; appears after beating {d.get('unlock', {}).get('beat', 'nobody')}.",
            "", "Deck pool (weights; the game deals 40 cards from it, three of a card at most):", ""]
    out += [f"- {nm(k)} ({v})" for k, v in sorted(deck.items(), key=lambda kv: -kv[1])]
    out += ["", "Prizes (weights out of 2048):", ""]
    for pool, cards in mod["drops"][d["id"]].items():
        out.append(f"- {pool.upper()}: " + ", ".join(f"{nm(k)} {v}" for k, v in cards.items()))
    out.append("")
if mod.get("equips"):
    out += ["## Equip cards", "", "| Card | Equips | Bonus |", "|---|---|---|"]
    for r in mod["equips"]:
        bonus = ", ".join((f"{k.replace('_', ' ')} {v:+}" if not isinstance(v, dict) else
                           f"{k.replace('_', ' ')} " + " ".join(f"{a} {b:+}" for a, b in v.items()))
                          for k, v in r.items() if k.startswith("bonus"))
        add = "any monster" if len(r["add"]) >= 20 else ", ".join(r["add"])
        out.append(f"| {spells[r['card']]['name']} | {add} | {bonus} |")
    out.append("")
if mod.get("rituals"):
    out += ["## Ritual cards", "", "| Card | Summons | Tributes |", "|---|---|---|"]
    for r in mod["rituals"]:
        if r.get("fusion"):
            out.append(f"| {spells[r['card']]['name']} | the strongest fusion of two or three monsters of the field "
                       f"| {len(r.get('recipes', []))} recipes of its own |")
            continue
        t = " + ".join(", ".join(f"{k.replace('_', ' ')} {v}" for k, v in x.items()) for x in r["tributes"])
        out.append(f"| {spells[r['card']]['name']} | {new[r['result']]['name']} | {t} |")
    out.append("")
out += ["## Fusion formulas", "",
        "Each result is stronger than both materials. Format: `A (ATK) + B (ATK) = Result (ATK)`.", ""]
by = {}
for r in mod["fusions"]:
    a, b = r["with"]
    for k in (a, b):
        if k in new:
            by.setdefault(k, []).append(r)
for k, c in sorted(new.items(), key=lambda kv: kv[1]["name"]):
    rules = by.get(k, [])
    if not rules and k in targets:
        continue
    out += [f"### {c['name']} ({c['attack']}) - {len(rules)} formulas", ""]
    for r in rules[:60]:
        (na, aa), (nb, ab), (nr, ar) = label(r["with"][0]), label(r["with"][1]), label(r["result"])
        out.append(f"- {na} ({aa}) + {nb} ({ab}) = {nr} ({ar})")
    if len(rules) > 60:
        out.append(f"- ... and {len(rules) - 60} more (all in mod.json)")
    out.append("")
(ROOT / "notes/real-cards-list.md").write_text("\n".join(out), encoding="utf-8")
print(len(out), "lines")
